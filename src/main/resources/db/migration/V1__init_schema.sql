-- Urban Company platform: full schema (PostgreSQL 16 + PostGIS)
CREATE EXTENSION IF NOT EXISTS postgis;

-- ---------- AUTH ----------
CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  phone VARCHAR(20) UNIQUE,
  email VARCHAR(160) UNIQUE,
  password_hash VARCHAR(100),
  full_name VARCHAR(120),
  role VARCHAR(20) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
  phone_verified BOOLEAN NOT NULL DEFAULT FALSE,
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------- LOCATION ----------
CREATE TABLE cities (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL UNIQUE,
  state VARCHAR(100),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  center_lat DOUBLE PRECISION NOT NULL,
  center_lng DOUBLE PRECISION NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE zones (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  city_id BIGINT NOT NULL REFERENCES cities(id),
  name VARCHAR(100) NOT NULL,
  center_lat DOUBLE PRECISION NOT NULL,
  center_lng DOUBLE PRECISION NOT NULL,
  radius_km DOUBLE PRECISION,
  polygon_coords TEXT,           -- "lat,lng;lat,lng;..." (optional polygon geofence; radius used if null)
  active BOOLEAN NOT NULL DEFAULT TRUE,
  geom geography(Point,4326) GENERATED ALWAYS AS (ST_SetSRID(ST_MakePoint(center_lng, center_lat),4326)::geography) STORED,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_zones_city ON zones(city_id);
CREATE INDEX idx_zones_geom ON zones USING GIST(geom);
CREATE TABLE addresses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id),
  label VARCHAR(30) NOT NULL,
  line1 VARCHAR(250) NOT NULL,
  line2 VARCHAR(250),
  landmark VARCHAR(150),
  city_id BIGINT NOT NULL REFERENCES cities(id),
  zone_id BIGINT NOT NULL REFERENCES zones(id),
  lat DOUBLE PRECISION NOT NULL,
  lng DOUBLE PRECISION NOT NULL,
  default_address BOOLEAN NOT NULL DEFAULT FALSE,
  geom geography(Point,4326) GENERATED ALWAYS AS (ST_SetSRID(ST_MakePoint(lng, lat),4326)::geography) STORED,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_addresses_user ON addresses(user_id);
CREATE INDEX idx_addresses_geom ON addresses USING GIST(geom);

-- ---------- CATALOG ----------
CREATE TABLE categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parent_id BIGINT REFERENCES categories(id),
  name VARCHAR(120) NOT NULL,
  slug VARCHAR(140) NOT NULL UNIQUE,
  icon_url VARCHAR(300),
  sort_order INT NOT NULL DEFAULT 0,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE services (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id BIGINT NOT NULL REFERENCES categories(id),
  name VARCHAR(150) NOT NULL,
  slug VARCHAR(170) NOT NULL UNIQUE,
  description TEXT,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_services_category ON services(category_id);
CREATE TABLE service_packages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  service_id BIGINT NOT NULL REFERENCES services(id),
  name VARCHAR(150) NOT NULL,
  description TEXT,
  base_price NUMERIC(10,2) NOT NULL,
  duration_minutes INT NOT NULL,
  max_quantity INT NOT NULL DEFAULT 1,
  instant_eligible BOOLEAN NOT NULL DEFAULT FALSE,
  attributes_json JSONB NOT NULL DEFAULT '{}'::jsonb,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_packages_service ON service_packages(service_id);
CREATE INDEX idx_packages_attrs ON service_packages USING GIN(attributes_json);
CREATE TABLE addon_questions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  package_id BIGINT NOT NULL REFERENCES service_packages(id),
  question_key VARCHAR(60) NOT NULL,
  question_text VARCHAR(300) NOT NULL,
  type VARCHAR(20) NOT NULL,
  required BOOLEAN NOT NULL DEFAULT FALSE,
  sort_order INT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (package_id, question_key)
);
CREATE TABLE addon_options (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  question_id BIGINT NOT NULL REFERENCES addon_questions(id) ON DELETE CASCADE,
  option_key VARCHAR(60) NOT NULL,
  label VARCHAR(200) NOT NULL,
  price_delta NUMERIC(10,2) NOT NULL DEFAULT 0,
  duration_delta_minutes INT NOT NULL DEFAULT 0,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (question_id, option_key)
);
CREATE TABLE rate_cards (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  service_id BIGINT NOT NULL REFERENCES services(id),
  item_name VARCHAR(150) NOT NULL,
  price NUMERIC(10,2) NOT NULL,
  unit VARCHAR(30) NOT NULL DEFAULT 'piece',
  description VARCHAR(300),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------- PARTNER ----------
CREATE TABLE commission_tiers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(60) NOT NULL,
  min_jobs INT NOT NULL,
  commission_percent NUMERIC(5,2) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE partners (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL UNIQUE REFERENCES users(id),
  display_name VARCHAR(120) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'PENDING_KYC',
  zone_id BIGINT REFERENCES zones(id),
  online BOOLEAN NOT NULL DEFAULT FALSE,
  rating_avg DOUBLE PRECISION NOT NULL DEFAULT 0,
  rating_count INT NOT NULL DEFAULT 0,
  acceptance_rate DOUBLE PRECISION NOT NULL DEFAULT 1,
  offers_received INT NOT NULL DEFAULT 0,
  offers_accepted INT NOT NULL DEFAULT 0,
  jobs_completed INT NOT NULL DEFAULT 0,
  active_jobs INT NOT NULL DEFAULT 0,
  bank_account_no VARCHAR(40),
  bank_ifsc VARCHAR(20),
  bank_holder VARCHAR(120),
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_partners_zone_status ON partners(zone_id, status);
CREATE TABLE partner_skills (
  partner_id BIGINT NOT NULL REFERENCES partners(id) ON DELETE CASCADE,
  category_id BIGINT NOT NULL REFERENCES categories(id),
  PRIMARY KEY (partner_id, category_id)
);
CREATE TABLE partner_documents (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  partner_id BIGINT NOT NULL REFERENCES partners(id),
  doc_type VARCHAR(30) NOT NULL,
  doc_number VARCHAR(60),
  file_url VARCHAR(400) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
  remarks VARCHAR(300),
  reviewed_by BIGINT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_partner_docs_partner ON partner_documents(partner_id);
CREATE TABLE partner_working_hours (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  partner_id BIGINT NOT NULL REFERENCES partners(id) ON DELETE CASCADE,
  day_of_week SMALLINT NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),
  start_time TIME NOT NULL,
  end_time TIME NOT NULL
);
CREATE INDEX idx_pwh_partner ON partner_working_hours(partner_id);
CREATE TABLE partner_leaves (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  partner_id BIGINT NOT NULL REFERENCES partners(id) ON DELETE CASCADE,
  start_at TIMESTAMPTZ NOT NULL,
  end_at TIMESTAMPTZ NOT NULL,
  reason VARCHAR(200)
);
CREATE INDEX idx_leaves_partner ON partner_leaves(partner_id, start_at);

-- ---------- PRICING / PROMO / MEMBERSHIP ----------
CREATE TABLE surge_rules (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  zone_id BIGINT REFERENCES zones(id),
  start_hour INT NOT NULL,
  end_hour INT NOT NULL,
  day_of_week INT,
  multiplier NUMERIC(4,2) NOT NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE coupons (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(40) NOT NULL UNIQUE,
  discount_type VARCHAR(10) NOT NULL,
  discount_value NUMERIC(10,2) NOT NULL,
  max_discount NUMERIC(10,2),
  min_order NUMERIC(10,2) NOT NULL DEFAULT 0,
  valid_from TIMESTAMPTZ,
  valid_to TIMESTAMPTZ,
  usage_limit INT,
  per_user_limit INT NOT NULL DEFAULT 1,
  used_count INT NOT NULL DEFAULT 0,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE coupon_redemptions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  coupon_id BIGINT NOT NULL REFERENCES coupons(id),
  user_id BIGINT NOT NULL REFERENCES users(id),
  booking_id BIGINT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_redemptions_user ON coupon_redemptions(coupon_id, user_id);
CREATE TABLE membership_plans (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(80) NOT NULL,
  price NUMERIC(10,2) NOT NULL,
  duration_days INT NOT NULL,
  discount_percent NUMERIC(5,2) NOT NULL,
  zero_convenience_fee BOOLEAN NOT NULL DEFAULT TRUE,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE memberships (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id),
  plan_id BIGINT NOT NULL REFERENCES membership_plans(id),
  start_at TIMESTAMPTZ NOT NULL,
  end_at TIMESTAMPTZ NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_memberships_user ON memberships(user_id, status, end_at);

-- ---------- WALLET / PAYMENTS ----------
CREATE TABLE wallets (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL UNIQUE REFERENCES users(id),
  balance NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (balance >= 0),
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE wallet_transactions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  wallet_id BIGINT NOT NULL REFERENCES wallets(id),
  type VARCHAR(10) NOT NULL,
  source VARCHAR(30) NOT NULL,
  amount NUMERIC(12,2) NOT NULL,
  balance_after NUMERIC(12,2) NOT NULL,
  reference VARCHAR(80),
  description VARCHAR(250),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_wtx_wallet ON wallet_transactions(wallet_id, id DESC);

-- ---------- BOOKINGS ----------
CREATE TABLE bookings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_code VARCHAR(24) NOT NULL UNIQUE,
  customer_id BIGINT NOT NULL REFERENCES users(id),
  partner_id BIGINT REFERENCES partners(id),
  address_id BIGINT REFERENCES addresses(id),
  category_id BIGINT NOT NULL REFERENCES categories(id),
  zone_id BIGINT NOT NULL REFERENCES zones(id),
  status VARCHAR(40) NOT NULL,
  instant BOOLEAN NOT NULL DEFAULT FALSE,
  scheduled_start TIMESTAMPTZ NOT NULL,
  scheduled_end TIMESTAMPTZ NOT NULL,
  duration_minutes INT NOT NULL,
  lat DOUBLE PRECISION NOT NULL,
  lng DOUBLE PRECISION NOT NULL,
  address_text VARCHAR(500),
  subtotal NUMERIC(12,2) NOT NULL DEFAULT 0,
  surge_amount NUMERIC(12,2) NOT NULL DEFAULT 0,
  membership_discount NUMERIC(12,2) NOT NULL DEFAULT 0,
  coupon_discount NUMERIC(12,2) NOT NULL DEFAULT 0,
  coupon_code VARCHAR(40),
  convenience_fee NUMERIC(12,2) NOT NULL DEFAULT 0,
  tax NUMERIC(12,2) NOT NULL DEFAULT 0,
  total NUMERIC(12,2) NOT NULL DEFAULT 0,
  extra_amount NUMERIC(12,2) NOT NULL DEFAULT 0,
  wallet_used NUMERIC(12,2) NOT NULL DEFAULT 0,
  paid_amount NUMERIC(12,2) NOT NULL DEFAULT 0,
  start_otp VARCHAR(4),
  end_otp VARCHAR(4),
  arrived_at TIMESTAMPTZ,
  started_at TIMESTAMPTZ,
  completed_at TIMESTAMPTZ,
  cancelled_at TIMESTAMPTZ,
  cancel_reason VARCHAR(300),
  cancelled_by VARCHAR(20),
  cancellation_fee NUMERIC(12,2) NOT NULL DEFAULT 0,
  refunded_amount NUMERIC(12,2) NOT NULL DEFAULT 0,
  warranty_of_booking_id BIGINT,
  warranty_expires_at TIMESTAMPTZ,
  search_started_at TIMESTAMPTZ,
  next_dispatch_at TIMESTAMPTZ,
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_bookings_customer ON bookings(customer_id, id DESC);
CREATE INDEX idx_bookings_partner ON bookings(partner_id, status);
CREATE INDEX idx_bookings_status ON bookings(status, scheduled_start);
CREATE INDEX idx_bookings_zone_cat ON bookings(zone_id, category_id, scheduled_start);
CREATE TABLE booking_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id BIGINT NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
  package_id BIGINT NOT NULL REFERENCES service_packages(id),
  package_name VARCHAR(150) NOT NULL,
  quantity INT NOT NULL,
  option_keys VARCHAR(500),
  unit_price NUMERIC(12,2) NOT NULL,
  line_total NUMERIC(12,2) NOT NULL,
  duration_minutes INT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_items_booking ON booking_items(booking_id);
CREATE TABLE booking_status_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id BIGINT NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
  from_status VARCHAR(40),
  to_status VARCHAR(40) NOT NULL,
  actor VARCHAR(20) NOT NULL,
  actor_id BIGINT,
  note VARCHAR(300),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_history_booking ON booking_status_history(booking_id, id);
CREATE TABLE extra_work_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id BIGINT NOT NULL REFERENCES bookings(id),
  partner_id BIGINT NOT NULL REFERENCES partners(id),
  description VARCHAR(500) NOT NULL,
  amount NUMERIC(12,2) NOT NULL,
  extra_minutes INT NOT NULL DEFAULT 0,
  status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
  resolved_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_extra_booking ON extra_work_requests(booking_id, status);
CREATE TABLE job_offers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id BIGINT NOT NULL REFERENCES bookings(id),
  partner_id BIGINT NOT NULL REFERENCES partners(id),
  status VARCHAR(20) NOT NULL,
  score DOUBLE PRECISION NOT NULL DEFAULT 0,
  radius_km INT NOT NULL,
  round_no INT NOT NULL,
  offered_at TIMESTAMPTZ NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL,
  responded_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_offers_booking ON job_offers(booking_id, status);
CREATE INDEX idx_offers_partner ON job_offers(partner_id, status);
CREATE INDEX idx_offers_expiry ON job_offers(status, expires_at);

-- ---------- PAYMENTS ----------
CREATE TABLE payments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  purpose VARCHAR(20) NOT NULL,
  booking_id BIGINT REFERENCES bookings(id),
  plan_id BIGINT REFERENCES membership_plans(id),
  user_id BIGINT NOT NULL REFERENCES users(id),
  amount NUMERIC(12,2) NOT NULL,
  wallet_amount NUMERIC(12,2) NOT NULL DEFAULT 0,
  method VARCHAR(20) NOT NULL,
  status VARCHAR(20) NOT NULL,
  intent_id VARCHAR(60) NOT NULL UNIQUE,
  gateway_ref VARCHAR(80),
  failure_reason VARCHAR(200),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_payments_booking ON payments(booking_id);
CREATE TABLE payment_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id VARCHAR(80) NOT NULL UNIQUE,
  payload TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE refunds (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id BIGINT NOT NULL REFERENCES bookings(id),
  amount NUMERIC(12,2) NOT NULL,
  wallet_amount NUMERIC(12,2) NOT NULL DEFAULT 0,
  gateway_amount NUMERIC(12,2) NOT NULL DEFAULT 0,
  status VARCHAR(20) NOT NULL,
  reason VARCHAR(300),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_refunds_booking ON refunds(booking_id);

-- ---------- EARNINGS ----------
CREATE TABLE partner_earnings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  partner_id BIGINT NOT NULL REFERENCES partners(id),
  booking_id BIGINT NOT NULL UNIQUE REFERENCES bookings(id),
  gross_amount NUMERIC(12,2) NOT NULL,
  commission_percent NUMERIC(5,2) NOT NULL,
  commission_amount NUMERIC(12,2) NOT NULL,
  tds_amount NUMERIC(12,2) NOT NULL,
  net_amount NUMERIC(12,2) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_earnings_partner ON partner_earnings(partner_id, id DESC);
CREATE TABLE withdrawal_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  partner_id BIGINT NOT NULL REFERENCES partners(id),
  amount NUMERIC(12,2) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'REQUESTED',
  bank_account_no VARCHAR(40),
  bank_ifsc VARCHAR(20),
